package kz.kaznaru.capstone.ui;

import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpServer;
import java.io.IOException;
import java.io.OutputStream;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;

/** Connects ApiController to the HTTP server that comes with the JDK (no framework). */
public class HttpApiServer {
    private final ApiController controller;
    private HttpServer server;

    public HttpApiServer(ApiController controller) {
        this.controller = controller;
    }

    public void start(int port) throws IOException {
        server = HttpServer.create(new InetSocketAddress(port), 0);
        server.createContext("/", this::handle);
        server.start();
    }

    public void stop() {
        if (server != null) {
            server.stop(0);
        }
    }

    private void handle(HttpExchange exchange) throws IOException {
        ApiResponse response = controller.handle(exchange.getRequestMethod(),
                exchange.getRequestURI().getPath(), exchange.getRequestURI().getRawQuery());
        byte[] bytes = response.body().getBytes(StandardCharsets.UTF_8);
        exchange.getResponseHeaders().set("Content-Type", "application/json; charset=utf-8");
        exchange.sendResponseHeaders(response.status(), bytes.length);
        try (OutputStream out = exchange.getResponseBody()) {
            out.write(bytes);
        }
    }
}
